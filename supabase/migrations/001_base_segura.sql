-- LIGA REGIONAL DE TENIS DE MESA LOS RÍOS
-- Hito 1: autenticación, perfiles y calendario público.
-- Ejecutar UNA vez en Supabase > SQL Editor, antes de registrar usuarios.
-- No incorpora todavía partidos, llaves, inscripciones ni ranking.

begin;

create type public.rol_usuario as enum ('administrador', 'juez_general', 'arbitro', 'jugador');

create table public.perfiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nombre_completo text not null default 'Usuario',
  rol public.rol_usuario not null default 'jugador',
  creado_en timestamptz not null default now(),
  constraint nombre_completo_tamano check (char_length(nombre_completo) between 1 and 120)
);

-- El rol NO se lee de user_metadata; cualquier usuario podría modificarlo.
-- Registro abierto = jugador. Solo un Administrador existente o SQL Editor cambia cargos.
create or replace function public.crear_perfil_nuevo_usuario()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.perfiles (id, nombre_completo, rol)
  values (
    new.id,
    left(coalesce(nullif(trim(new.raw_user_meta_data ->> 'full_name'), ''), 'Usuario'), 120),
    'jugador'::public.rol_usuario
  );
  return new;
end;
$$;

create trigger al_crear_usuario_auth
  after insert on auth.users
  for each row execute function public.crear_perfil_nuevo_usuario();

-- Función auxiliar segura para políticas RLS; SECURITY DEFINER evita recursión.
create or replace function public.es_administrador()
returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.perfiles
    where id = (select auth.uid()) and rol = 'administrador'::public.rol_usuario
  );
$$;

create or replace function public.es_juez_general()
returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.perfiles
    where id = (select auth.uid()) and rol = 'juez_general'::public.rol_usuario
  );
$$;

create table public.temporadas (
  id bigint generated by default as identity primary key,
  nombre text not null,
  anio integer not null unique,
  creado_en timestamptz not null default now(),
  constraint temporada_nombre_valido check (char_length(trim(nombre)) between 1 and 100),
  constraint temporada_anio_valido check (anio between 2020 and 2100)
);

create table public.fechas (
  id bigint generated by default as identity primary key,
  temporada_id bigint not null references public.temporadas(id) on delete restrict,
  numero integer not null,
  fecha date not null,
  comuna text not null,
  recinto text not null,
  estado text not null default 'borrador',
  creado_en timestamptz not null default now(),
  constraint fechas_numero_valido check (numero between 1 and 100),
  constraint fechas_estado_valido check (estado in ('borrador', 'publicada', 'finalizada')),
  constraint fechas_comuna_valido check (char_length(trim(comuna)) between 1 and 100),
  constraint fechas_recinto_valido check (char_length(trim(recinto)) between 1 and 150),
  constraint fecha_numero_por_temporada unique(temporada_id, numero)
);

create index fechas_publicadas_por_dia on public.fechas(fecha) where estado = 'publicada';
create index perfiles_por_rol on public.perfiles(rol);

alter table public.perfiles enable row level security;
alter table public.temporadas enable row level security;
alter table public.fechas enable row level security;

-- Perfiles: cada uno solo consulta el suyo. Administrador puede consultar y editar.
-- No existe una política para INSERT desde cliente ni UPDATE por el propio usuario.
create policy perfiles_ver_propio_o_admin on public.perfiles
  for select to authenticated
  using (id = (select auth.uid()) or (select public.es_administrador()));

create policy perfiles_editar_solo_admin on public.perfiles
  for update to authenticated
  using ((select public.es_administrador()))
  with check ((select public.es_administrador()));

-- Temporadas: la información básica no es confidencial.
create policy temporadas_lectura on public.temporadas
  for select to anon, authenticated using (true);
create policy temporadas_crear_admin on public.temporadas
  for insert to authenticated with check ((select public.es_administrador()));
create policy temporadas_editar_admin on public.temporadas
  for update to authenticated
  using ((select public.es_administrador())) with check ((select public.es_administrador()));
create policy temporadas_borrar_admin on public.temporadas
  for delete to authenticated using ((select public.es_administrador()));

-- Fechas: anónimo solo ve fechas publicadas. Administrador y Juez General
-- pueden consultar también borradores. Solo Administrador las crea/edita aquí.
create policy fechas_publicas on public.fechas
  for select to anon using (estado = 'publicada');
create policy fechas_autenticados on public.fechas
  for select to authenticated
  using (estado = 'publicada' or (select public.es_administrador()) or (select public.es_juez_general()));
create policy fechas_crear_admin on public.fechas
  for insert to authenticated with check ((select public.es_administrador()));
create policy fechas_editar_admin on public.fechas
  for update to authenticated
  using ((select public.es_administrador())) with check ((select public.es_administrador()));
create policy fechas_borrar_admin on public.fechas
  for delete to authenticated using ((select public.es_administrador()));

-- Las funciones auxiliares son invocadas por las políticas para los autenticados.
revoke all on function public.crear_perfil_nuevo_usuario() from public, anon, authenticated;
revoke all on function public.es_administrador() from public;
revoke all on function public.es_juez_general() from public;
grant execute on function public.es_administrador() to authenticated;
grant execute on function public.es_juez_general() to authenticated;

-- Privilegios de PostgREST: RLS es la segunda y decisiva capa de autorización.
grant select on public.perfiles to authenticated;
grant update on public.perfiles to authenticated;
grant select on public.temporadas to anon, authenticated;
grant insert, update, delete on public.temporadas to authenticated;
grant select on public.fechas to anon, authenticated;
grant insert, update, delete on public.fechas to authenticated;
grant usage, select on all sequences in schema public to authenticated;

commit;
